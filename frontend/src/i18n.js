const LangContext = createContext(null);

const resolve = (obj, key) => key.split(".").reduce((o, k) => (o == null ? undefined : o[k]), obj);

export const LanguageProvider = ({ children }) => {
  const [lang, setLangState] = useState(() => localStorage.getItem("source-lang") || "en");
  const setLang = (l) => {
    setLangState(l);
    localStorage.setItem("source-lang", l);
  };
  const t = (key) => resolve(translations[lang], key) ?? resolve(translations.en, key) ?? key;
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
};

export const useLang = () => useContext(LangContext);
